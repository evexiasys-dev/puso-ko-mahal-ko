// Evexia is in Santa Rosa, so its barangays are suggested before other cities'.
BARANGAY_ENTRIES.sort(function (a, b) { return (b.city === 'Santa Rosa') - (a.city === 'Santa Rosa'); });

// Prefix matches first, then substring matches. Accent-insensitive, so
// typing "binan" matches "Biñan".
const COMBINING_DIACRITICS_RE = /[\u0300-\u036f]/g;

function normalize(s){
  return (s || '').toLowerCase().normalize('NFD').replace(COMBINING_DIACRITICS_RE, '');
}

function rank(query, items, getText){
  const q = normalize(query).trim();
  if (!q) return [];
  const starts = [];
  const contains = [];
  for (const item of items){
    const text = normalize(getText(item));
    if (text.startsWith(q)) starts.push(item);
    else if (text.includes(q)) contains.push(item);
  }
  return [...starts, ...contains];
}

function searchBarangays(query, limit = 8){
  return rank(query, BARANGAY_ENTRIES, e => e.barangay).slice(0, limit);
}

window.PHAddressBook = { searchBarangays: searchBarangays };
